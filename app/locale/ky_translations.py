def po_unescape(s):
    return s.replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')


def po_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def main():
    po = Path(__file__).resolve().parent / 'ky' / 'LC_MESSAGES' / 'django.po'
    lines = po.read_text(encoding='utf-8').splitlines()
    out, i, missing, filled = [], 0, [], 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('msgid "'):
            parts = [line[7:-1]]
            j = i + 1
            while j < len(lines) and lines[j].startswith('"'):
                parts.append(lines[j][1:-1]); j += 1
            msgid = po_unescape(''.join(parts))
            # пропускаем старый msgstr (может быть многострочным)
            k = j
            if k < len(lines) and lines[k].startswith('msgstr "'):
                k += 1
                while k < len(lines) and lines[k].startswith('"'):
                    k += 1
            out.extend(lines[i:j])
            if msgid == '':
                out.extend(lines[j:k])  # заголовок
            elif msgid in KY:
                out.append(f'msgstr "{po_escape(KY[msgid])}"'); filled += 1
            else:
                out.extend(lines[j:k]); missing.append(msgid)
            i = k
            continue
        if line.startswith('#, fuzzy') and out and out[-1].startswith('#'):
            i += 1
            continue
        out.append(line); i += 1
    text = '\n'.join(out) + '\n'
    text = text.replace('"Language: \\n"', '"Language: ky\\n"').replace('#, fuzzy\n', '', 1)
    po.write_text(text, encoding='utf-8')
    print(f'переведено: {filled}, без перевода: {len(missing)}')
    for m in missing:
        print('  -', repr(m))
    return 1 if missing else 0


if __name__ == '__main__':
    sys.exit(main())
